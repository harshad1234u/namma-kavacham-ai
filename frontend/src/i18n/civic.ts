const CIVIC: Record<string, CivicStrings> = { en, hi, ta };

/** Strings for the chosen language, English when the UI has no translation yet (`fallback` = true). */
export function useCivic(): { c: CivicStrings; fallback: boolean; langName: string } {
  const { code } = useLanguage();
  return { c: CIVIC[code] ?? en, fallback: !(code in CIVIC), langName: langInfo(code).name };
}

export const fill = (s: string, vars: Record<string, string | number>) =>
  s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));

/** Dynamic key lookup (e.g. `status_${s}`) that only ever returns text; falls back to the key itself. */
export function str(c: CivicStrings, key: string): string {
  const v = (c as unknown as Record<string, unknown>)[key];
  return typeof v === "string" ? v : key;
}
